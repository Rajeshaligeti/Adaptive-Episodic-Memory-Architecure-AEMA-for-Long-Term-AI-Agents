import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional
from fpdf import FPDF

def clean_text(s: str) -> str:
    """Replaces non-latin1 characters with ASCII equivalents."""
    if not isinstance(s, str):
        s = str(s)
    return (
        s.replace("—", "-")
        .replace("–", "-")
        .replace("“", '"')
        .replace("”", '"')
        .replace("’", "'")
        .replace("‘", "'")
        .replace("≥", ">=")
        .replace("≤", "<=")
        .replace("∑", "SUM")
        .replace("τ", "tau")
        .replace("•", "-")
        .encode("ascii", "replace")
        .decode("ascii")
    )

class AEMAPdfReport(FPDF):
    def __init__(self, experiment_id: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.experiment_id = experiment_id
        self.set_auto_page_break(auto=True, margin=15)
        
    def header(self):
        self.set_fill_color(15, 23, 42) # Slate-900 Dark Navy
        self.rect(0, 0, 210, 18, "F")
        self.set_xy(10, 5)
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(255, 255, 255)
        self.cell(100, 8, "AEMA LAB | Machine Learning Research Report", align="L")
        self.set_font("Helvetica", "", 8)
        self.set_text_color(203, 213, 225)
        self.cell(90, 8, clean_text(f"ID: {self.experiment_id[:12]}..."), align="R")
        self.ln(18)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, clean_text(f"Page {self.page_no()}/{{nb}} - Generated by AEMA LAB (Adaptive Ensemble Intelligence)"), align="C")

class ReportGenerator:
    @staticmethod
    def generate_experiment_report(
        experiment_data: dict[str, Any],
        dataset_data: dict[str, Any],
        output_path: str,
        comparison_data: Optional[list[dict[str, Any]]] = None
    ) -> str:
        """Generates a professional multi-page PDF experiment report."""
        exp_id = experiment_data.get("id", "Unknown")
        pdf = AEMAPdfReport(experiment_id=exp_id)
        pdf.alias_nb_pages()
        pdf.add_page()
        
        # 1. Title Banner
        pdf.set_fill_color(248, 250, 252)
        pdf.set_draw_color(226, 232, 240)
        pdf.rect(10, 22, 190, 26, "DF")
        
        pdf.set_xy(15, 25)
        pdf.set_font("Helvetica", "B", 16)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(180, 8, clean_text(f"Clustering Experiment: {experiment_data.get('algorithm_name', 'AEMA')}"), ln=True)
        
        pdf.set_x(15)
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(100, 116, 139)
        dt_str = experiment_data.get("created_at", str(datetime.now(timezone.utc)))
        pdf.cell(180, 6, clean_text(f"Generated: {dt_str} | Dataset: {dataset_data.get('original_name', 'N/A')}"), ln=True)
        
        pdf.ln(10)
        
        # 2. Key Metrics Summary Grid (Cards)
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 8, "1. Executive Metrics Summary", ln=True)
        
        metrics = experiment_data.get("metrics", {})
        card_w = 45
        card_h = 20
        y_cards = pdf.get_y()
        
        cards = [
            ("Clusters", str(metrics.get("clusters_count", 0)), (238, 242, 255), (79, 70, 229)),
            ("Silhouette", str(metrics.get("silhouette_score", "N/A")), (236, 253, 245), (16, 185, 129)),
            ("Davies-Bouldin", str(metrics.get("davies_bouldin_index", "N/A")), (254, 242, 242), (239, 68, 68)),
            ("Calinski-Harabasz", str(metrics.get("calinski_harabasz_index", "N/A")), (255, 251, 235), (217, 119, 6)),
        ]
        
        for idx, (title, val, bg, text_c) in enumerate(cards):
            x = 10 + idx * 48
            pdf.set_fill_color(*bg)
            pdf.set_draw_color(226, 232, 240)
            pdf.rect(x, y_cards, card_w, card_h, "DF")
            
            pdf.set_xy(x + 2, y_cards + 2)
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(100, 116, 139)
            pdf.cell(card_w - 4, 4, clean_text(title), align="C")
            
            pdf.set_xy(x + 2, y_cards + 8)
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(*text_c)
            pdf.cell(card_w - 4, 8, clean_text(val), align="C")
            
        pdf.set_y(y_cards + card_h + 6)
        
        # 3. Dataset & Preprocessing Details
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 8, "2. Dataset & Preprocessing Profile", ln=True)
        
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(51, 65, 85)
        meta_lines = [
            f"- Original Filename: {dataset_data.get('original_name', 'N/A')}",
            f"- Dimensions: {dataset_data.get('row_count', 0)} rows x {dataset_data.get('column_count', 0)} columns",
            f"- Noise / Archived Outliers: {metrics.get('noise_points', 0)} ({metrics.get('noise_ratio', 0.0) * 100:.1f}%)",
            f"- Pipeline Execution Time: {metrics.get('execution_time_ms', 0):.2f} ms"
        ]
        for line in meta_lines:
            pdf.cell(0, 5, clean_text(line), ln=True)
            
        pdf.ln(4)
        
        # 4. Cluster Distribution Table
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 8, "3. Cluster Size & Member Distribution", ln=True)
        
        dist = metrics.get("cluster_distribution", [])
        if dist:
            # Header
            pdf.set_fill_color(241, 245, 249)
            pdf.set_draw_color(203, 213, 225)
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(50, 7, "Cluster Partition", 1, 0, "C", True)
            pdf.cell(60, 7, "Sample Count", 1, 0, "C", True)
            pdf.cell(60, 7, "Percentage of Total", 1, 1, "C", True)
            
            pdf.set_font("Helvetica", "", 9)
            for item in dist:
                lbl = item.get("label", f"Cluster {item.get('cluster')}")
                cnt = str(item.get("count", 0))
                pct = f"{item.get('percentage', 0.0)}%"
                pdf.cell(50, 6, clean_text(lbl), 1, 0, "L")
                pdf.cell(60, 6, clean_text(cnt), 1, 0, "R")
                pdf.cell(60, 6, clean_text(pct), 1, 1, "R")
        else:
            pdf.cell(0, 5, "No distribution details available.", ln=True)
            
        pdf.ln(6)
        
        # 5. Algorithm Comparison Table (if available)
        if comparison_data:
            pdf.set_font("Helvetica", "B", 12)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(0, 8, "4. Multi-Algorithm Benchmark Comparison", ln=True)
            
            pdf.set_fill_color(241, 245, 249)
            pdf.set_draw_color(203, 213, 225)
            pdf.set_font("Helvetica", "B", 8)
            pdf.cell(40, 6, "Algorithm", 1, 0, "C", True)
            pdf.cell(25, 6, "Clusters", 1, 0, "C", True)
            pdf.cell(30, 6, "Silhouette", 1, 0, "C", True)
            pdf.cell(30, 6, "Davies-Bouldin", 1, 0, "C", True)
            pdf.cell(35, 6, "Calinski-Harabasz", 1, 0, "C", True)
            pdf.cell(30, 6, "Runtime (ms)", 1, 1, "C", True)
            
            pdf.set_font("Helvetica", "", 8)
            for row in comparison_data:
                algo = row.get("algorithm", "N/A")
                k_val = str(row.get("clusters_count", "N/A"))
                sil = str(row.get("silhouette_score", "-"))
                db = str(row.get("davies_bouldin_index", "-"))
                ch = str(row.get("calinski_harabasz_index", "-"))
                t_ms = f"{row.get('execution_time_ms', 0):.1f}"
                
                is_aema = (algo == "AEMA")
                if is_aema:
                    pdf.set_font("Helvetica", "B", 8)
                    pdf.set_fill_color(238, 242, 255)
                else:
                    pdf.set_font("Helvetica", "", 8)
                    pdf.set_fill_color(255, 255, 255)
                    
                pdf.cell(40, 5, clean_text(algo), 1, 0, "L", is_aema)
                pdf.cell(25, 5, clean_text(k_val), 1, 0, "C", is_aema)
                pdf.cell(30, 5, clean_text(sil), 1, 0, "R", is_aema)
                pdf.cell(30, 5, clean_text(db), 1, 0, "R", is_aema)
                pdf.cell(35, 5, clean_text(ch), 1, 0, "R", is_aema)
                pdf.cell(30, 5, clean_text(t_ms), 1, 1, "R", is_aema)
                
            pdf.ln(6)
            
        # 6. AEMA Research Methodology & Equations
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 8, "5. AEMA Theoretical Framework & Equations", ln=True)
        
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(71, 85, 105)
        notes = (
            "The Adaptive Ensemble-based Machine Learning Approach (AEMA) synthesizes hierarchical "
            "agglomerative clustering, dynamic validation-index weighting, consensus co-association "
            "matrix aggregation, and sample confidence scoring.\n\n"
            "Key Mathematical Formulations (ICSCNA 2026 Reference):\n"
            "1. Base Co-association Consensus: C_ij = SUM(w_m * I(c_i^(m) == c_j^(m))) where SUM(w_m) = 1.\n"
            "2. Adaptive Sample Scoring: Score(x_i) = w_r * R_i + w_f * F_i + w_c * C_i\n"
            "   - R_i: Local density/recency proxy (1 - d_k / max(d_k))\n"
            "   - F_i: Consensus agreement frequency with cluster members\n"
            "   - C_i: Normalized cluster size and coherence proxy\n"
            "3. Strategic Archival: Samples with Score(x_i) < tau (default 0.30) are archived/flagged as noise.\n"
            "4. Consensus Partitioning: Average-linkage agglomerative clustering on dissimilarity matrix D = 1 - C."
        )
        pdf.multi_cell(190, 4.5, clean_text(notes))
        
        pdf.ln(4)
        pdf.set_font("Helvetica", "I", 8)
        pdf.set_text_color(148, 163, 184)
        pdf.cell(0, 5, clean_text("Reference: B.V. Raju Institute of Technology, Dept. of CSE (AI&ML) - Paper ID: ICSCNA_230"), ln=True)
        
        # Save output
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        pdf.output(output_path)
        return output_path
